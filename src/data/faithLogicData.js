export function searchFaithLogic(query) {
  if (!query || query.trim().length < 2) return [];
  const q = query.toLowerCase().trim();

  const results = [];
  Object.values(FAITH_LOGIC_BOOKS).forEach(book => {
    book.chapters.forEach(ch => {
      const matchTitle = ch.titleBangla.toLowerCase().includes(q) || ch.titleEnglish.toLowerCase().includes(q);
      const matchSummary = ch.summary.toLowerCase().includes(q);
      const matchQuote = ch.quote.toLowerCase().includes(q);
      const matchAllegation = ch.logicMatrix?.allegation.toLowerCase().includes(q);
      const matchCore = ch.logicMatrix?.coreArgument.toLowerCase().includes(q);

      if (matchTitle || matchSummary || matchQuote || matchAllegation || matchCore) {
        results.push({
          bookId: book.id,
          bookTitle: book.titleBangla,
          chapter: ch,
          score: matchTitle ? 3 : matchAllegation ? 2 : 1
        });
      }
    });
  });

  return results.sort((a, b) => b.score - a.score);
}
