/** Current language state */
let currentLang = 'bn';

/** 
 * Get a translation string
 * @param {string} key - Translation key
 * @param {object} [vars] - Variables for interpolation
 * @returns {string}
 */
export function t(key, vars = {}) {
  let str = translations[currentLang]?.[key] || translations.bn[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

/** Get current language */
export function getLang() {
  return currentLang;
}

/** Set language and update HTML attributes */
export function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem('eqra-lang', lang);
}

/** Initialize language from URL or storage */
export function initLang(lang) {
  const stored = localStorage.getItem('eqra-lang');
  const detected = lang || stored || 'bn';
  setLang(detected);
  return currentLang;
}

export default { t, getLang, setLang, initLang };
